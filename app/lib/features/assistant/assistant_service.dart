import 'chat_message.dart';

/// Контракт ассистента. Локальная реализация — заглушка на правилах;
/// в проде заменяется на вызов Claude API через наш backend
/// (POST /assistant/chat), при этом UI не меняется.
abstract interface class AssistantService {
  Future<String> reply(String userMessage, List<ChatMessage> history);
}

/// Локальный ассистент на ключевых словах (без сети).
class LocalAssistantService implements AssistantService {
  static const _disclaimer =
      '\n\nℹ️ Это справочная поддержка, не замена консультации врача.';

  @override
  Future<String> reply(String userMessage, List<ChatMessage> history) async {
    await Future<void>.delayed(const Duration(milliseconds: 600));
    return _canned(userMessage) + _disclaimer;
  }

  String _canned(String q) {
    final t = q.toLowerCase();
    if (t.contains('тошнот') || t.contains('токсикоз')) {
      return 'Тошнота в первом триместре — частое явление. Помогают дробное питание '
          'маленькими порциями, сухарик утром до подъёма и достаточно воды. '
          'Если рвота частая и мешает есть/пить — сообщите врачу.';
    }
    if (t.contains('шевел') || t.contains('толч')) {
      return 'Считать шевеления удобно во второй половине дня: в норме — не менее '
          '10 эпизодов за 2 часа. Заметное снижение активности малыша — повод '
          'связаться с врачом. В приложении есть «Счётчик толчков».';
    }
    if (t.contains('вес') || t.contains('прибав')) {
      return 'Рекомендуемая прибавка зависит от исходного ИМТ (для нормального — '
          'примерно 11.5–16 кг за всю беременность). Отслеживать удобно в сервисе '
          '«Монитор веса мамы».';
    }
    if (t.contains('схватк') || t.contains('роды')) {
      return 'Ориентир «пора в роддом» — правило 5-1-1: схватки каждые ~5 минут, '
          'по ~1 минуте, в течение ~1 часа. Засекать удобно в «Счётчике схваток».';
    }
    if (t.contains('пита') || t.contains('еда') || t.contains('есть')) {
      return 'Питайтесь разнообразно: овощи, фрукты, белок, цельные злаки. '
          'Избегайте сырого мяса/рыбы, непастеризованных продуктов и алкоголя. '
          'Подробнее — в сервисе «Что можно есть».';
    }
    if (t.contains('температ') || t.contains('боль') || t.contains('кров')) {
      return 'Высокая температура, сильная боль или кровянистые выделения требуют '
          'внимания врача — не откладывайте обращение, при необходимости вызовите '
          'скорую.';
    }
    return 'Спасибо за вопрос! Я помогу разобраться с беременностью и развитием '
        'малыша. Уточните тему — например, «тошнота», «шевеления», «вес», '
        '«схватки» или «питание».';
  }
}
